import { test } from "node:test";
import assert from "node:assert/strict";
import { spawn } from "node:child_process";
import { once } from "node:events";
import { createServer } from "node:net";
import { fileURLToPath } from "node:url";
import { setTimeout as delay } from "node:timers/promises";
import { createTypeScriptLoader } from "./load-typescript.mjs";

test("frontend client and store integrate with isolated FastAPI: auth, ownership, catalog, images and versions", { timeout: 90000 }, async (t) => {
  const listener = createServer().listen(0, "127.0.0.1");
  await once(listener, "listening");
  const port = listener.address().port;
  await new Promise((resolve) => listener.close(resolve));
  const backend = fileURLToPath(new URL("../../backend/", import.meta.url));
  const python = process.platform === "win32" ? backend + ".venv/Scripts/python.exe" : backend + ".venv/bin/python";
  const child = spawn(python, ["-B", "tests/frontend_api_fixture.py", String(port)], { cwd: backend, stdio: ["ignore", "ignore", "pipe"] });
  let errors = "";
  let spawnError;
  child.on("error", (error) => { spawnError = error; });
  child.stderr.on("data", (chunk) => { errors += chunk; });
  const originalFetch = globalThis.fetch;
  const originalUrl = process.env.NEXT_PUBLIC_API_URL;
  const originalStorage = globalThis.localStorage;
  t.after(async () => {
    if (errors) console.error(errors);
    globalThis.fetch = originalFetch;
    if (originalUrl === undefined) delete process.env.NEXT_PUBLIC_API_URL;
    else process.env.NEXT_PUBLIC_API_URL = originalUrl;
    if (originalStorage === undefined) delete globalThis.localStorage;
    else globalThis.localStorage = originalStorage;
    if (child.pid && child.exitCode === null) {
      const closed = once(child, "exit"); child.kill(); await closed;
    }
  });
  const base = `http://127.0.0.1:${port}`;
  let ready = false;
  for (let attempt = 0; attempt < 150; attempt++) {
    if (spawnError) throw spawnError;
    if (child.exitCode !== null) throw new Error(errors || "Fixture server exited");
    try { ready = (await originalFetch(base + "/api/v1/health/live")).ok; } catch { /* Wait for uvicorn. */ }
    if (ready) break;
    await delay(200);
  }
  assert.ok(ready, "Fixture API did not start: " + errors);
  process.env.NEXT_PUBLIC_API_URL = base;
  const records = new Map();
  globalThis.localStorage = { getItem: (key) => records.get(key) ?? null, setItem: (key, value) => records.set(key, value) };
  let cookie = "";
  const requests = [];
  globalThis.fetch = async (url, options = {}) => {
    const headers = new Headers(options.headers);
    headers.set("Origin", "http://localhost:3000");
    if (cookie) headers.set("Cookie", cookie);
    const response = await originalFetch(url, { ...options, headers });
    requests.push({ path: new URL(url).pathname, status: response.status, cookieSent: headers.has("Cookie") });
    const setCookie = response.headers.get("set-cookie");
    if (setCookie) cookie = setCookie.split(";")[0];
    return response;
  };
  const react = "data:text/javascript," + encodeURIComponent("export const useSyncExternalStore = (_subscribe, getSnapshot) => getSnapshot();");
  const load = createTypeScriptLoader({ react });
  const auth = await load("../src/lib/auth-api.ts");
  const store = await load("../src/lib/store.ts");
  const { catalogApi } = await load("../src/lib/catalog-api.ts");
  const { initialDraft } = await load("../src/lib/demo-data.ts");
  await store.loadWorkspace();
  assert.equal(store.useWorkspace().status, "unauthenticated");
  await auth.register("first@example.com", "password123", "First");
  store.setSession(await auth.login("first@example.com", "password123"));
  await store.loadWorkspace();
  assert.equal(store.useWorkspace().status, "ready", JSON.stringify({ requests, error: store.useWorkspace().error }));
  assert.deepEqual(store.useDemo().products, []);
  let product = await store.saveProduct({ id: "", name: "Canvas bag", category: "Accessories", price: 120.5, description: "Everyday canvas bag", features: "Canvas\nZipper", warranty: "", delivery: "Dhaka", returns: "", image: "", art: "tote", archived: false });
  assert.match(product.id, /^\d+$/);
  product = await store.saveProduct({ ...product, price: 150.75 });
  const png = Buffer.from("iVBORw0KGgoAAAANSUhEUgAAAAIAAAACCAIAAAD91JpzAAAAC0lEQVR4nGNgQAYAAA4AAamRc7EAAAAASUVORK5CYII=", "base64");
  const image = await store.uploadProductImage(product.id, new File([png], "bag.png", { type: "image/png" }));
  product = await store.refreshProduct(product.id);
  assert.match(product.image, /storage.example\/signed/);
  await store.removeProductImage(product.id, String(image.id));
  assert.equal(store.useDemo().products[0].image, "");
  await assert.rejects(catalogApi.uploadImage(product.id, new File(["bad"], "bad.png", { type: "image/png" })), (error) => error.status === 422);
  assert.equal(store.useDemo().products.length, 1);
  await store.duplicateProduct(product.id);
  assert.equal(store.useDemo().products.length, 2);
  await store.archiveProduct(product.id, true);
  assert.equal(store.useDemo().products.find((p) => p.id === product.id).archived, true);
  await store.archiveProduct(product.id, false);
  let post = await store.savePost({ ...initialDraft.post, id: "", productId: product.id, headline: "Canvas bag", body: "A useful canvas bag for your everyday needs.", hashtags: "#bag #canvas" });
  assert.equal(post.versionNumber, 1);
  post = await store.savePost({ ...post, headline: "Better bag", offer: "Save today" });
  assert.equal(post.versionNumber, 2);
  assert.equal(post.versions[0].headline, "Canvas bag");
  assert.equal((await store.savePost(post)).versionNumber, 2);
  await store.loadWorkspace();
  assert.equal(store.useDemo().posts[0].versionNumber, 2);
  assert.equal(store.useDemo().products.find((p) => p.id === product.id).price, 150.75);
  await auth.logout(); store.clearSession();
  await auth.register("second@example.com", "password123", "Second");
  store.setSession(await auth.login("second@example.com", "password123"));
  await store.loadWorkspace();
  assert.deepEqual(store.useDemo().products, []);
  assert.deepEqual(store.useDemo().posts, []);
  await assert.rejects(catalogApi.product(product.id), (error) => error.status === 404);
  await auth.logout(); store.clearSession();
  store.setSession(await auth.login("first@example.com", "password123"));
  await store.loadWorkspace();
  await store.deletePost(post.id);
  assert.deepEqual(store.useDemo().posts, []);
  await store.deleteProduct(product.id);
  assert.equal(store.useDemo().products.length, 1);
  await auth.logout(); store.clearSession();
  await store.loadWorkspace();
  assert.equal(store.useWorkspace().status, "unauthenticated");
});
